async function addGrants() {
  console.log('🌱 Adding real Australian grants...');
  let added = 0;

  for (const grant of REAL_GRANTS) {
    const existing = await prisma.opportunity.findFirst({ where: { title: grant.title } });
    if (!existing) {
      await prisma.opportunity.create({ data: grant as any });
      added++;
    }
  }

  console.log(`✅ Added ${added} new grants`);
}

addGrants()
  .then(() => prisma.$disconnect())
  .then(() => process.exit(0))
  .catch((e) => {
    console.error(e);
    prisma.$disconnect();
    process.exit(1);
  });
